"""Regenerate the exact BF16-to-MX runtime code lookup from the C reference."""

from __future__ import annotations

import argparse
import ctypes
from pathlib import Path
import struct
import subprocess


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "mx_gemmini_support/runtime_quant.c"
OUTPUT = ROOT / "mx_gemmini_support/runtime_quant_lut.h"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workdir", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args()
    work = args.workdir.resolve()
    work.mkdir(parents=True, exist_ok=True)
    wrapper = work / "quant_lut_reference.c"
    wrapper.write_text(
        '#include "runtime_quant.c"\n'
        'uint8_t mx_reference_code(float value, uint32_t format) {\n'
        '  return element_code(value, format);\n}\n', encoding="utf-8")
    library = work / "quant_lut_reference.so"
    subprocess.run([
        "cc", "-O2", "-fno-fast-math", "-fPIC", "-shared",
        "-DMX_QUANT_LUT_GENERATOR", "-I", str(SOURCE.parent),
        str(wrapper), "-o", str(library)], check=True)
    reference = ctypes.CDLL(str(library)).mx_reference_code
    reference.argtypes = [ctypes.c_float, ctypes.c_uint32]
    reference.restype = ctypes.c_uint8
    lines = [
        "/* Generated by tools/generate_runtime_quant_lut.py from runtime_quant.c. */",
        "#ifndef MX_GEMMINI_RUNTIME_QUANT_LUT_H",
        "#define MX_GEMMINI_RUNTIME_QUANT_LUT_H",
    ]
    for precision in (4, 8):
        lines.append(f"static const uint8_t mx_fp{precision}_code_lut[16][128] = {{")
        for delta in range(16):
            values = []
            for mantissa in range(128):
                bits = ((127 - delta) << 23) | (mantissa << 16)
                value = struct.unpack("<f", struct.pack("<I", bits))[0]
                values.append(reference(value, precision))
            lines.append("  {")
            for offset in range(0, 128, 16):
                lines.append("    " + ", ".join(
                    f"0x{code:02x}" for code in values[offset:offset + 16]) + ",")
            lines.append("  },")
        lines.append("};")
    lines.append("#endif")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(args.out)


if __name__ == "__main__":
    main()
